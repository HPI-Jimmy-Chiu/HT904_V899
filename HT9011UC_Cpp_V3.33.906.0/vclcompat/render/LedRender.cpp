void RenderLed(HDC hdc, const RECT& destRect, const LedCore& core)
{
    const LedAsset& asset = AssetFor(core.GetLEDStyle());
    int sw = 0, sh = 0;
    NativeSize(asset, sw, sh);
    if (sw <= 0 || sh <= 0) return;

    HDC     memdc  = ::CreateCompatibleDC(hdc);
    HBITMAP hbmp   = ::CreateCompatibleBitmap(hdc, sw, sh);
    HGDIOBJ oldBmp = ::SelectObject(memdc, hbmp);

    // aled.pas:106-159 CreateLedBitmap: LoadImage() the named resource, then
    // (below, outside this blit) flood-fill it once with the target colour.
    const BITMAPINFO* bi   = reinterpret_cast<const BITMAPINFO*>(asset.dib);
    const unsigned char* bits =
        asset.dib + sizeof(BITMAPINFOHEADER) + 16 * sizeof(RGBQUAD);
    ::SetDIBitsToDevice(memdc, 0, 0, sw, sh, 0, 0, 0, sh, bits, bi, DIB_RGB_COLORS);

    // aled.pas Paint/OnLedTimer: `fLedBitmap[Integer(ColorTemp)]` -- index 0
    // is the bitmap CreateLedBitmap flood-filled with fTrueColor, index 1
    // with fFalseColor (aled.pas:156-159). ColorTemp==false selects index 0
    // (TrueColor), ==true selects index 1 (FalseColor) -- see LedCore.h's
    // own note on why this polarity looks backwards but is golden's own.
    TColor fillColor = core.ColorTemp ? core.GetFalseColor() : core.GetTrueColor();
    HBRUSH  fillBrush = ::CreateSolidBrush(ResolveColor(fillColor));
    HGDIOBJ oldBrush  = ::SelectObject(memdc, fillBrush);
    // AI(W906-W7-C2) 20260728: flood seed = THE STYLE EXTENTS, deliberately
    // NOT the live control size and NOT the bitmap's native size.
    //
    // aled.pas:157/159 is `Canvas.FloodFill(Width DIV 2, Height DIV 2, clLime,
    // fsSurface)`, and `Width`/`Height` there are indeed TALed's own
    // properties -- but READ THE ENCLOSING SCOPE before concluding anything
    // from that: both FloodFill calls sit INSIDE CreateLedBitmap
    // (aled.pas:106-160), immediately after the `case fLEDStyle` ladder has
    // JUST assigned Width/Height to that style's fixed extents
    // (aled.pas:114-115 / 121-122 / 128-129 / 135-136 / 142-143 / 149-150).
    // So at the instant golden floods, Width/Height ARE the style extents, by
    // construction. A .dfm may later override the control's size (e.g. golden
    // cContact.dfm:15895 ledOneCycle is a LEDSqLarge sized 15x15), but that
    // happens AFTER CreateLedBitmap has already run and golden never re-runs
    // it on a size change -- so golden's seed is PERMANENTLY the style
    // extents and can never observe the .dfm size.
    //
    // Two earlier attempts at this line were both wrong, recorded here so
    // they are not retried:
    //   * seeding at the RESOURCE's native centre (sw/2, sh/2) differs from
    //     the style extents only for LEDSqSmall (style 22x22, ALEDSQSM
    //     natively 16x16) -- and even there both seeds land in the same
    //     contiguous clLime lens, so it produced no observable difference.
    //   * seeding at the LIVE control centre (core.Width/2, core.Height/2)
    //     is a real fidelity REGRESSION: it diverges for the 262 of 1,840
    //     live LED instances whose .dfm size differs from their style
    //     extents, and for ledOneCycle above the seed (7,7) falls outside
    //     the lens entirely, rendering 0 coloured pixels where golden
    //     renders 189.
    int floodX = 0, floodY = 0;
    StyleExtents(core.GetLEDStyle(), floodX, floodY);
    floodX /= 2;
    floodY /= 2;
    // Clamp into the bitmap's addressable range. Only LEDSqSmall can exceed
    // it (style 22x22 vs a 16x16 bitmap -> 11 clamps to 15, still inside the
    // lens), so this never changes the filled region for any of the 6 styles;
    // it exists so ExtFloodFill can never be handed an out-of-bounds point.
    if (floodX > sw - 1) floodX = sw - 1;
    if (floodX < 0)       floodX = 0;
    if (floodY > sh - 1) floodY = sh - 1;
    if (floodY < 0)       floodY = 0;
    // aled.pas:157/159 `Canvas.FloodFill(Width DIV 2, Height DIV 2, clLime,
    // fsSurface)` -- fsSurface==FLOODFILLSURFACE, replacing the contiguous
    // clLime==RGB(0,255,0) "lens" region (verified present at every one of
    // these 6 bitmaps' centre pixel, all sharing the same 16-colour VGA
    // palette with index 10==RGB(0,255,0)) with the CURRENTLY SELECTED
    // brush -- exactly `fillBrush` above.
    ::ExtFloodFill(memdc, floodX, floodY, RGB(0, 255, 0), FLOODFILLSURFACE);
    ::SelectObject(memdc, oldBrush);
    ::DeleteObject(fillBrush);

    // `Canvas->StretchDraw(Rect(0,0,Width,Height), fLedBitmap[...])` --
    // stretches from the bitmap's native (sw,sh) to the caller's destRect
    // (== core.Width/Height in every real .dfm instance, see file banner).
    int dw = destRect.right - destRect.left;
    int dh = destRect.bottom - destRect.top;
    ::StretchBlt(hdc, destRect.left, destRect.top, dw, dh,
                 memdc, 0, 0, sw, sh, SRCCOPY);

    ::SelectObject(memdc, oldBmp);
    ::DeleteObject(hbmp);
    ::DeleteDC(memdc);
}

void RenderLed(HDC hdc, int x, int y, const LedCore& core)
{
    RECT dest;
    dest.left = x; dest.top = y;
    dest.right = x + core.Width; dest.bottom = y + core.Height;
    RenderLed(hdc, dest, core);
}

