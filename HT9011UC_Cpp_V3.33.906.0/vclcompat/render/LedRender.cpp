struct LedAsset {
    const unsigned char* dib;
    unsigned long        dibSize;
};

// Order matches TLEDStyle's declared enumerator order (LedCore.h) --
// LEDSmall,LEDLarge,LEDSqSmall,LEDSqLarge,LEDVertical,LEDHorizontal, itself
// preserved verbatim from aled.pas's own declared Pascal enum order.
const LedAsset kLedAssets[6] = {
    { kAled_ALEDSM,   sizeof(kAled_ALEDSM)   },   // LEDSmall      (aled.pas:112-118)
    { kAled_ALEDLG,   sizeof(kAled_ALEDLG)   },   // LEDLarge      (aled.pas:119-125)
    { kAled_ALEDSQSM, sizeof(kAled_ALEDSQSM) },   // LEDSqSmall    (aled.pas:126-132)
    { kAled_ALEDSQLG, sizeof(kAled_ALEDSQLG) },   // LEDSqLarge    (aled.pas:133-139)
    { kAled_ALEDVT,   sizeof(kAled_ALEDVT)   },   // LEDVertical   (aled.pas:147-153)
    { kAled_ALEDHZ,   sizeof(kAled_ALEDHZ)   },   // LEDHorizontal (aled.pas:140-146)
};

const LedAsset& AssetFor(TLEDStyle style)
{
    // kLedAssets above is written out in TLEDStyle's own declared
    // enumerator order (LedCore.h: LEDSmall=0, LEDLarge=1, LEDSqSmall=2,
    // LEDSqLarge=3, LEDVertical=4, LEDHorizontal=5), so a direct index is
    // safe and avoids a parallel switch/table pair drifting out of sync.
    return kLedAssets[(int)style];
}

// Reads BITMAPINFOHEADER.biWidth/biHeight straight out of the embedded
// blob -- deliberately NOT taken from LedCore::Width/Height (see the
// LEDSqSmall GOLDEN QUIRK note at the top of this file for why those two
// can legitimately differ).
void NativeSize(const LedAsset& asset, int& w, int& h)
{
    BITMAPINFOHEADER hdr;
    // Blobs are byte-for-byte a packed BITMAPINFOHEADER at offset 0 (see
    // file banner); memcpy avoids any alignment/strict-aliasing concern
    // reinterpret_cast'ing the raw `unsigned char*` would raise.
    std::memcpy(&hdr, asset.dib, sizeof(BITMAPINFOHEADER));
    w = hdr.biWidth;
    h = hdr.biHeight;   // positive == bottom-up, which is what these all are
}

// AI(W906-W7-C2) 20260728: the per-style FIXED extents golden's
// CreateLedBitmap assigns to Width/Height (aled.pas:114-115 / 121-122 /
// 128-129 / 135-136 / 142-143 / 149-150), needed here because golden's
// FloodFill seed is evaluated inside CreateLedBitmap and therefore always
// sees these values rather than any later .dfm override -- see the seed
// derivation in RenderLed below for the full reasoning.
//
// This table is duplicated from LedCore::ApplyStyleExtents (vclcompat/
// LedCore.cpp:35-49) rather than shared, because the two serve different
// layers (core state vs. renderer geometry) and the renderer must not depend
// on the core having been style-synced. Both cite the SAME golden lines, so
// if one is ever edited the other must be too.
void StyleExtents(TLEDStyle style, int& w, int& h)
{
    switch (style) {
        case LEDSmall:      w = 22; h = 22; break;   // aled.pas:112-118
        case LEDLarge:      w = 32; h = 32; break;   // aled.pas:119-125
        case LEDSqSmall:    w = 22; h = 22; break;   // aled.pas:126-132
        case LEDSqLarge:    w = 22; h = 22; break;   // aled.pas:133-139
        case LEDHorizontal: w = 22; h = 14; break;   // aled.pas:140-146
        case LEDVertical:   w = 14; h = 22; break;   // aled.pas:147-153
        default:            w = 0;  h = 0;  break;
    }
}

