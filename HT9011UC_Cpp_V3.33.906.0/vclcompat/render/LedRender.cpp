//  type==2/RT_BITMAP, matching aled.pas:106-159's 6 named LoadImage() calls)
//  via a one-off Python RES-format parser (walks the standard Win32 .RES
//  entry layout: DataSize/HeaderSize, TYPE, NAME, DataVersion/MemoryFlags/
//  LanguageId/Version/Characteristics, then DataSize bytes of payload,
//  DWORD-aligned) -- not hand-transcribed. Each blob is exactly what a
//  Win32 RT_BITMAP resource stores: a packed DIB with NO BITMAPFILEHEADER
//  (BITMAPINFOHEADER(40B) + a 16-colour RGBQUAD palette(64B) + 4bpp
//  bottom-up pixel bits), which is precisely the shape SetDIBitsToDevice's
//  BITMAPINFO*/bits-pointer pair expects -- no repacking needed.
//
//  GOLDEN QUIRK (discovered while extracting this table, not previously
//  called out anywhere): aled.pas's LEDSqSmall case (:126-132) sets the
//  control's Width/Height to 22x22, but the ALEDSQSM bitmap it loads is
//  natively 16x16 (verified against this exact resource, not assumed by
//  symmetry with the other 5 styles, all of which DO match their control's
//  declared Width/Height exactly). Since `Canvas->StretchDraw` always
//  stretches to whatever target rect it's given regardless of source size,
//  golden's own Paint() for a LEDSqSmall control genuinely upscales a
//  16x16 bitmap to 22x22 -- a real, if minor, visual quirk. LEDSqSmall has
//  0 live .dfm instances (plan §6-W7-C1), so this is not reachable in
//  practice. This renderer reproduces ONLY the StretchDraw-upscale half of
//  the quirk faithfully (it always uses the RESOURCE's own native
//  width/height, read from each blob's own BITMAPINFOHEADER, as the
//  StretchBlt SOURCE size, never the LedCore's Width/Height). The
//  flood-fill origin is a SEPARATE spot golden does NOT read from the
//  bitmap's native size: aled.pas:157/159 flood-fills at
//  (Width DIV 2, Height DIV 2) using the CONTROL's own Width/Height, so for
//  LEDSqSmall that is (11,11) against a 16x16 bitmap, not (8,8) as the
//  bitmap's own centre would be -- see RenderLed's flood-origin comment
//  below for the fix (AI(W906-W7-C2) 20260728) that makes this half faithful
//  too, clamped into the bitmap's valid pixel range for safety.
// ===========================================================================
